def load_env_file(path: Path) -> None:
    if not path.exists():
        return

    with path.open("r", encoding="utf-8") as env_file:
        for line in env_file:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            if key and key not in os.environ:
                os.environ[key] = value


def synchsafe_size(size: int) -> bytes:
    return bytes(
        [
            (size >> 21) & 0x7F,
            (size >> 14) & 0x7F,
            (size >> 7) & 0x7F,
            size & 0x7F,
        ]
    )


def read_synchsafe_size(data: bytes) -> int:
    return (data[0] << 21) | (data[1] << 14) | (data[2] << 7) | data[3]


def id3_text_frame(frame_id: str, value: str | int | None) -> bytes:
    if value is None or str(value).strip() == "":
        return b""

    payload = b"\x01" + str(value).encode("utf-16")
    return frame_id.encode("ascii") + len(payload).to_bytes(4, "big") + b"\x00\x00" + payload


def id3_url_frame(frame_id: str, value: str | None) -> bytes:
    if not value or not value.startswith(("http://", "https://")):
        return b""

    payload = value.encode("ascii", errors="ignore")
    return frame_id.encode("ascii") + len(payload).to_bytes(4, "big") + b"\x00\x00" + payload


def guess_image_mime_type(url: str, content_type: str | None) -> str:
    content_type = (content_type or "").split(";", 1)[0].strip().lower()
    if content_type in {"image/jpeg", "image/png"}:
        return content_type

    path = urlparse(url).path.lower()
    if path.endswith(".png"):
        return "image/png"
    return "image/jpeg"


def fetch_artwork(artwork_url: str | None) -> tuple[str, bytes] | None:
    if not artwork_url:
        return None

    request = Request(artwork_url, headers={"User-Agent": "MDL/1.0"})
    try:
        with urlopen(request, timeout=20) as response:
            content_type = response.headers.get("Content-Type")
            image = response.read(10 * 1024 * 1024 + 1)
    except (HTTPError, URLError, TimeoutError, OSError) as exc:
        print(f"[metadata] artwork skipped: {exc}")
        return None

    if len(image) > 10 * 1024 * 1024:
        print("[metadata] artwork skipped: image is larger than 10 MB")
        return None

    return guess_image_mime_type(artwork_url, content_type), image


def id3_apic_frame(artwork: tuple[str, bytes] | None) -> bytes:
    if not artwork:
        return b""

    mime_type, image = artwork
    payload = b"\x00" + mime_type.encode("ascii") + b"\x00\x03\x00" + image
    return b"APIC" + len(payload).to_bytes(4, "big") + b"\x00\x00" + payload


def strip_existing_id3v2(data: bytes) -> bytes:
    if len(data) < 10 or data[:3] != b"ID3":
        return data

    flags = data[5]
    tag_size = 10 + read_synchsafe_size(data[6:10])
    if flags & 0x10:
        tag_size += 10
    return data[tag_size:]


def write_mp3_metadata(path: Path, track: TrackMetadata) -> None:
    frames = b"".join(
        [
            id3_text_frame("TIT2", track.track),
            id3_text_frame("TPE1", track.artists.replace(";", "/")),
            id3_text_frame("TPE2", track.artists.split(";", 1)[0].strip()),
            id3_text_frame("TALB", track.album),
            id3_text_frame("TYER", track.year),
            id3_text_frame("TRCK", track.track_number),
            id3_url_frame("WOAS", track.source_url),
            id3_apic_frame(fetch_artwork(track.artwork_url)),
        ]
    )
    if not frames:
        return

    tag = b"ID3\x03\x00\x00" + synchsafe_size(len(frames)) + frames
    data = strip_existing_id3v2(path.read_bytes())
    path.write_bytes(tag + data)
    print("[metadata] tagged mp3")


def normalized_words(value: str) -> set[str]:
    return {word for word in WORD_CHARS.sub(" ", value.casefold()).split() if word}


def normalized_text(value: str) -> str:
    return " ".join(WORD_CHARS.sub(" ", value.casefold()).split())


def normalized_compact_text(value: str) -> str:
    return WORD_CHARS.sub("", value.casefold())


def primary_artist_words(artists: str) -> set[str]:
    primary = re.split(r";|,|&|\bfeat\.?\b|\bft\.?\b", artists, flags=re.I)[0]
    return normalized_words(primary)


def candidate_duration_ms(candidate: dict) -> int | None:
    duration = candidate.get("duration")
    if isinstance(duration, (int, float)):
        return int(duration * 1000)
    duration_string = candidate.get("duration_string")
    if not isinstance(duration_string, str) or ":" not in duration_string:
        return None

    total = 0
    for part in duration_string.split(":"):
        if not part.isdigit():
            return None
        total = total * 60 + int(part)
    return total * 1000


def youtube_candidate_url(candidate: dict) -> str | None:
    for key in ("webpage_url", "original_url", "url"):
        value = candidate.get(key)
        if isinstance(value, str) and value.startswith(("http://", "https://")):
            return value
    video_id = candidate.get("id")
    if video_id:
        return f"https://www.youtube.com/watch?v={video_id}"
    return None


def youtube_match_details(track: TrackMetadata, candidate: dict) -> dict[str, object]:
    title = str(candidate.get("title") or "")
    channel = str(candidate.get("channel") or candidate.get("uploader") or "")
    haystack_words = normalized_words(f"{title} {channel}")
    track_words = normalized_words(track.track)
    artist_words = primary_artist_words(track.artists)
    album_words = normalized_words(track.album)
    track_compact = normalized_compact_text(track.track)
    title_compact = normalized_compact_text(title)
    expected_duration = track.duration_ms
    actual_duration = candidate_duration_ms(candidate)
    duration_delta = abs(expected_duration - actual_duration) if expected_duration and actual_duration else None
    title_exact = bool(track_words and track_words.issubset(haystack_words))
    title_compact_exact = bool(track_compact and track_compact in title_compact)

    return {
        "title_words": track_words,
        "artist_words": artist_words,
        "album_words": album_words,
        "haystack_words": haystack_words,
        "title_exact": title_exact or title_compact_exact,
        "title_word_exact": title_exact,
        "title_compact_exact": title_compact_exact,
        "artist_exact": bool(artist_words and artist_words.issubset(haystack_words)),
        "title_overlap": len(track_words.intersection(haystack_words)),
        "artist_overlap": len(artist_words.intersection(haystack_words)),
        "duration_delta": duration_delta,
    }


def score_youtube_candidate(track: TrackMetadata, candidate: dict) -> tuple[int, list[str]]:
    title = str(candidate.get("title") or "")
    channel = str(candidate.get("channel") or candidate.get("uploader") or "")
    haystack = normalized_text(f"{title} {channel}")
    details = youtube_match_details(track, candidate)
    haystack_words = details["haystack_words"]
    track_words = details["title_words"]
    artist_words = details["artist_words"]
    album_words = details["album_words"]

    score = 0
    reasons: list[str] = []

    if details["title_exact"]:
        score += 45
        reasons.append("title" if details["title_word_exact"] else "title-compact")
    else:
        overlap = int(details["title_overlap"])
        if overlap:
            score += min(25, overlap * 8)
            reasons.append("partial-title")

    if details["artist_exact"]:
        score += 35
        reasons.append("artist")
    else:
        overlap = int(details["artist_overlap"])
        if overlap:
            score += min(20, overlap * 8)
            reasons.append("partial-artist")

    if album_words and album_words.intersection(haystack_words):
        score += 8
        reasons.append("album")

    if any(phrase in haystack for phrase in GOOD_MATCH_PHRASES):
        score += 12
        reasons.append("official-ish")

    delta = details["duration_delta"]
    if isinstance(delta, int):
        if delta <= 3000:
            score += 35
            reasons.append("duration-exact")
        elif delta <= 10000:
            score += 22
            reasons.append("duration-close")
        elif delta <= 30000:
            score += 8
            reasons.append("duration-near")
        else:
            score -= 25
            reasons.append("duration-far")

    real_track_words = track_words
    for bad_word in BAD_MATCH_WORDS:
        if bad_word in haystack_words and bad_word not in real_track_words:
            score -= 16
            reasons.append(f"penalty-{bad_word}")

    view_count = candidate.get("view_count")
    if isinstance(view_count, int):
        if view_count >= 1_000_000:
            score += 5
        elif view_count < 1_000:
            score -= 3

    return score, reasons


def youtube_match_rank(track: TrackMetadata, candidate: dict, score: int) -> tuple[int, int, int, int]:
    details = youtube_match_details(track, candidate)
    title_exact = bool(details["title_exact"])
    artist_exact = bool(details["artist_exact"])
    title_overlap = int(details["title_overlap"])
    artist_overlap = int(details["artist_overlap"])
    duration_delta = details["duration_delta"]

    if title_exact and artist_exact and isinstance(duration_delta, int) and duration_delta <= 5000:
        return (5, -duration_delta, score, 0)

    if isinstance(duration_delta, int) and duration_delta <= 10000 and title_exact and (
        artist_exact or artist_overlap > 0
    ):
        return (4, -duration_delta, score, artist_overlap)

    if isinstance(duration_delta, int) and duration_delta <= 10000 and title_overlap > 0 and artist_overlap > 0:
        return (3, -duration_delta, score, title_overlap + artist_overlap)

    if title_exact and artist_exact:
        duration_penalty = -duration_delta if isinstance(duration_delta, int) else -999999
        return (2, duration_penalty, score, 0)

    return (1, score, -(duration_delta or 999999), title_overlap + artist_overlap)


def read_youtube_search_candidates(
    track: TrackMetadata,
    cookie_args: list[str],
    search_results: int,
) -> list[dict]:
    query_text = f"{track.artists} - {track.track} {track.album}".translate(PUNCTUATION_TRANSLATION)
    query = f"ytsearch{search_results}:{query_text}"
    cmd = [
        "yt-dlp",
        "--flat-playlist",
        "--dump-single-json",
        "--skip-download",
        "--ignore-errors",
        "--no-warnings",
        *cookie_args,
        query,
    ]
    completed = subprocess.run(cmd, check=False, capture_output=True, text=True)
    if not completed.stdout.strip():
        message = completed.stderr.strip() or f"yt-dlp exited with status {completed.returncode}"
        raise RuntimeError(f"Could not search YouTube for {track.artists} - {track.track}: {message}")

    try:
        data = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        message = completed.stderr.strip() or f"yt-dlp exited with status {completed.returncode}"
        raise RuntimeError(f"Could not parse YouTube search results for {track.artists} - {track.track}: {message}") from exc

    return [entry for entry in data.get("entries") or [] if isinstance(entry, dict)]


def resolve_download_url(
    track: TrackMetadata,
    cookie_args: list[str],
    search_results: int,
    min_score: int,
) -> str:
    if track.source_url:
        return track.source_url

    candidates = read_youtube_search_candidates(track, cookie_args, search_results)
    rejected_for_duration = []
    scored = []
    for candidate in candidates:
        if not youtube_candidate_url(candidate):
            continue
        details = youtube_match_details(track, candidate)
        duration_delta = details["duration_delta"]
        if track.duration_ms and isinstance(duration_delta, int) and duration_delta > 10000:
            rejected_for_duration.append((duration_delta, candidate))
            continue
        scored.append((score_youtube_candidate(track, candidate), candidate))

    if not scored:
        if rejected_for_duration:
            best_rejected = min(rejected_for_duration, key=lambda item: item[0])
            title = best_rejected[1].get("title") or youtube_candidate_url(best_rejected[1])
            delta_seconds = best_rejected[0] / 1000
            raise RuntimeError(
                f"No YouTube matches within 10 seconds of ListenBrainz duration. "
                f"Closest was {delta_seconds:.1f}s off: {title}"
            )
        raise RuntimeError(f"No usable YouTube search results for: {track.artists} - {track.track}")

    scored.sort(
        key=lambda item: youtube_match_rank(track, item[1], item[0][0]),
        reverse=True,
    )
    (score, reasons), best = scored[0]
    url = youtube_candidate_url(best)
    title = best.get("title") or url
    if score < min_score:
        raise RuntimeError(
            f"Best YouTube match scored {score}, below --youtube-min-score {min_score}: {title}"
        )

    print(f"[match] {score} ({', '.join(reasons)}) {title}")
    return str(url)


def download_track(
    track: TrackMetadata,
    output_dir: Path,
    dry_run: bool,
    cookie_args: list[str],
    search_results: int,
    min_score: int,
) -> TrackResult:
    if dry_run:
        download_url = track.source_url or f"ytsearch{search_results}:{track.artists} - {track.track} {track.album}"
        print(f"[dry-run] {download_url} -> {track.destination}")
        return TrackResult("dry-run", track.artists, track.track, track.destination, playlist_title=track.playlist_title)

    destination_dir = track.destination.parent

    if track.destination.exists():
        print(f"[skip] {track.destination}")
        write_mp3_metadata(track.destination, track)
        return TrackResult("skipped", track.artists, track.track, track.destination, playlist_title=track.playlist_title)

    destination_dir.mkdir(parents=True, exist_ok=True)

    download_url = resolve_download_url(track, cookie_args, search_results, min_score)

    with tempfile.TemporaryDirectory(prefix="spotify-yt-", dir=output_dir) as tmp:
        temp_dir = Path(tmp)
        cmd = [
            "yt-dlp",
            "--quiet",
            "--no-warnings",
            *cookie_args,
            "-x",
            "--audio-format",
            "mp3",
            "--audio-quality",
            "0",
            "-o",
            str(temp_dir / "%(title).200B [%(id)s].%(ext)s"),
            download_url,
        ]

        print(f"[download] {track.artists} - {track.track}")
        subprocess.run(cmd, check=True)

        mp3s = sorted(temp_dir.glob("*.mp3"), key=lambda item: item.stat().st_mtime, reverse=True)
        if not mp3s:
            raise RuntimeError(f"yt-dlp did not produce an mp3 for: {track.artists} - {track.track}")

        write_mp3_metadata(mp3s[0], track)
        shutil.move(str(mp3s[0]), track.destination)
        print(f"[saved] {track.destination}")
        return TrackResult("downloaded", track.artists, track.track, track.destination, playlist_title=track.playlist_title)


def print_summary(results: list[TrackResult]) -> None:
    downloaded = [result for result in results if result.status == "downloaded"]
    skipped = [result for result in results if result.status == "skipped"]
    dry_runs = [result for result in results if result.status == "dry-run"]
    failed = [result for result in results if result.status == "failed"]

    print("\nSummary")
    print(f"  Downloaded: {len(downloaded)}")
    print(f"  Skipped:    {len(skipped)}")
    print(f"  Dry runs:   {len(dry_runs)}")
    print(f"  Failed:     {len(failed)}")

    def print_result_group(title: str, group: list[TrackResult], include_error: bool = False) -> None:
        if not group:
            return

        print(f"\n{title}")
        for result in group:
            if result.destination:
                print(f"  - {result.label} -> {result.destination}")
            else:
                print(f"  - {result.label}")

            if include_error and result.error:
                print(f"    error: {result.error}")

    print_result_group("Downloaded", downloaded)
    print_result_group("Skipped", skipped)
    print_result_group("Dry Run", dry_runs)
    print_result_group("Failed", failed, include_error=True)


