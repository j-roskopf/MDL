def sync_plex_playlists(results: list[TrackResult], args: argparse.Namespace) -> bool:
    plex_url, plex_token = load_plex_credentials(args)
    if not plex_url and not plex_token:
        return True
    if not plex_url or not plex_token:
        print("Plex sync needs both --plex-url and --plex-token, or PLEX_URL and PLEX_TOKEN.", file=sys.stderr)
        return False
    if args.dry_run:
        print("[plex] Skipping Plex sync during dry run")
        return True

    usable = [
        result
        for result in results
        if result.status in {"downloaded", "skipped"} and result.destination and result.playlist_title
    ]
    if not usable:
        print("[plex] No playlist-backed downloaded/skipped tracks to sync")
        return True

    try:
        root = plex_request_xml(plex_url, plex_token, "/")
        machine_id = root.get("machineIdentifier")
        if not machine_id:
            raise RuntimeError("Could not read Plex machineIdentifier from server root.")

        if args.plex_section_id:
            print(f"[plex] Refreshing library section {args.plex_section_id}")
            plex_request_xml(
                plex_url,
                plex_token,
                f"/library/sections/{quote(str(args.plex_section_id))}/refresh",
            )
            if args.plex_scan_wait > 0:
                time.sleep(args.plex_scan_wait)

        file_rating_keys: dict[str, str] = {}
        if args.plex_section_id:
            print(f"[plex] Reading library file map for section {args.plex_section_id}")
            file_rating_keys = plex_library_file_map(plex_url, plex_token, args.plex_section_id)
            print(f"[plex] Loaded {len(file_rating_keys)} Plex file path(s)")

        grouped: dict[str, list[TrackResult]] = {}
        for result in usable:
            grouped.setdefault(result.playlist_title or "ListenBrainz", []).append(result)

        for playlist_title, playlist_results in grouped.items():
            rating_keys: list[str] = []
            unmatched = playlist_results
            for attempt in range(1, args.plex_match_retries + 1):
                next_unmatched: list[TrackResult] = []
                for result in unmatched:
                    rating_key = plex_find_track_rating_key(
                        plex_url,
                        plex_token,
                        result,
                        args.plex_path_map,
                        file_rating_keys,
                    )
                    if rating_key:
                        rating_keys.append(rating_key)
                        if args.plex_section_id and not args.no_plex_lock_track_titles:
                            plex_lock_track_title(
                                plex_url,
                                plex_token,
                                args.plex_section_id,
                                rating_key,
                                result.track,
                            )
                    else:
                        next_unmatched.append(result)

                unmatched = next_unmatched
                if not unmatched or attempt >= args.plex_match_retries:
                    break

                print(
                    f"[plex] Waiting for Plex to index {len(unmatched)} unmatched track(s) "
                    f"before retry {attempt + 1}/{args.plex_match_retries}"
                )
                time.sleep(args.plex_match_wait)
                if args.plex_section_id:
                    file_rating_keys = plex_library_file_map(plex_url, plex_token, args.plex_section_id)

            for result in unmatched:
                print(f"[plex] Could not match in Plex: {result.label}")

            if not rating_keys:
                print(f"[plex] No Plex tracks found for playlist: {playlist_title}")
                continue

            existing = plex_existing_audio_playlist(plex_url, plex_token, playlist_title)
            if existing is not None:
                if not args.plex_replace_playlists:
                    print(f"[plex] Playlist already exists, leaving it alone: {playlist_title}")
                    continue
                rating_key = existing.get("ratingKey")
                if rating_key:
                    plex_delete_playlist(plex_url, plex_token, rating_key)

            plex_create_audio_playlist(plex_url, plex_token, machine_id, playlist_title, rating_keys)
            print(f"[plex] Created playlist '{playlist_title}' with {len(rating_keys)} track(s)")
    except (RuntimeError, ET.ParseError) as exc:
        print(f"[plex] {exc}", file=sys.stderr)
        return False

    return True


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Download Spotify, YouTube Music, CSV, and ListenBrainz playlists from YouTube.",
        epilog=(
            "Examples:\n"
            "  ./downloader.py playlist1.csv playlist2.csv\n"
            "  ./downloader.py 'https://open.spotify.com/track/...' "
            "'https://open.spotify.com/album/...'\n"
            "  ./downloader.py playlist.csv 'https://open.spotify.com/playlist/...'\n"
            "  ./downloader.py 'https://music.youtube.com/playlist?list=...'\n"
            "  ./downloader.py listenbrainz:joebrothehobo"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "sources",
        nargs="+",
        help="CSV path(s), Spotify URL(s), YouTube Music URL(s), or ListenBrainz source(s).",
    )
    parser.add_argument("-o", "--output-dir", default=Path("Music"), type=Path)
    parser.add_argument("--limit", type=int, help="Download only the first N tracks.")
    parser.add_argument("--dry-run", action="store_true", help="Show searches and output paths without downloading.")
    parser.add_argument(
        "--youtube-search-results",
        type=int,
        default=10,
        help="Number of YouTube search results to score for metadata-only tracks. Default: 10.",
    )
    parser.add_argument(
        "--youtube-min-score",
        type=int,
        default=50,
        help="Minimum score required before downloading a YouTube search match. Default: 50.",
    )
    parser.add_argument(
        "--cookies-from-browser",
        metavar="BROWSER",
        help="Use browser cookies for YouTube, for example: chrome, safari, firefox, edge, brave.",
    )
    parser.add_argument(
        "--cookies",
        type=Path,
        help="Use a cookies.txt file for YouTube authentication.",
    )
    parser.add_argument(
        "--spotify-client-id",
        help="Spotify API client ID. Defaults to SPOTIFY_CLIENT_ID.",
    )
    parser.add_argument(
        "--spotify-client-secret",
        help="Spotify API client secret. Defaults to SPOTIFY_CLIENT_SECRET.",
    )
    parser.add_argument("--plex-url", help="Plex server URL. Defaults to PLEX_URL.")
    parser.add_argument("--plex-token", help="Plex token. Defaults to PLEX_TOKEN.")
    parser.add_argument(
        "--plex-section-id",
        help="Optional Plex music library section ID to refresh before playlist creation.",
    )
    parser.add_argument(
        "--plex-scan-wait",
        type=int,
        default=20,
        help="Seconds to wait after a Plex library refresh before searching for tracks. Default: 20.",
    )
    parser.add_argument(
        "--plex-match-retries",
        type=int,
        default=3,
        help="Number of Plex matching attempts after refresh. Default: 3.",
    )
    parser.add_argument(
        "--plex-match-wait",
        type=int,
        default=30,
        help="Seconds to wait between Plex matching attempts. Default: 30.",
    )
    parser.add_argument(
        "--plex-path-map",
        action="append",
        default=[],
        metavar="LOCAL=PLEX",
        help="Map local output paths to Plex-visible paths, for example /Users/me/Music=/music.",
    )
    parser.add_argument(
        "--plex-replace-playlists",
        action="store_true",
        help="Delete and recreate matching Plex audio playlists instead of leaving existing playlists untouched.",
    )
    parser.add_argument(
        "--no-plex-lock-track-titles",
        action="store_true",
        help="Do not edit/lock Plex track titles to the downloaded metadata title.",
    )
    return parser.parse_args()


def main() -> int:
    load_env_file(Path(".env"))
    args = parse_args()
    output_dir = args.output_dir.expanduser().resolve()

    if shutil.which("yt-dlp") is None and not args.dry_run:
        print("yt-dlp is not installed or is not on PATH.", file=sys.stderr)
        return 1

    if args.cookies_from_browser and args.cookies:
        print("Use either --cookies-from-browser or --cookies, not both.", file=sys.stderr)
        return 1

    cookie_args = build_cookie_args(args)

    try:
        tracks = read_sources(args.sources, output_dir, args, cookie_args)
    except RuntimeError as exc:
        print(exc, file=sys.stderr)
        return 1

    if args.limit is not None:
        tracks = tracks[: args.limit]

    results: list[TrackResult] = []
    for index, track in enumerate(tracks, start=1):
        try:
            print(f"\n[{index}/{len(tracks)}]")
            results.append(
                download_track(
                    track,
                    output_dir,
                    args.dry_run,
                    cookie_args,
                    args.youtube_search_results,
                    args.youtube_min_score,
                )
            )
        except (RuntimeError, subprocess.CalledProcessError) as exc:
            error = str(exc)
            results.append(
                TrackResult(
                    "failed",
                    track.artists,
                    track.track,
                    track.destination,
                    error=error,
                    playlist_title=track.playlist_title,
                )
            )
            print(f"[error] {error}", file=sys.stderr)

    print_summary(results)

    plex_ok = sync_plex_playlists(results, args)

    if any(result.status == "failed" for result in results):
        return 1
    if not plex_ok:
        return 1

    print("\nDone.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
