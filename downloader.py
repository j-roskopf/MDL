@dataclass
class TrackResult:
    status: str
    artists: str
    track: str
    destination: Path | None = None
    error: str | None = None
    playlist_title: str | None = None

    @property
    def label(self) -> str:
        return f"{self.artists} - {self.track}"


@dataclass
class TrackMetadata:
    track: str
    artists: str
    album: str
    destination: Path
    source_url: str | None = None
    year: str | None = None
    track_number: int | None = None
    artwork_url: str | None = None
    playlist_title: str | None = None
    duration_ms: int | None = None


